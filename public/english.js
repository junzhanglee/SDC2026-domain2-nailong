export function english(value) {
  if (typeof value !== 'string') return value;
  if (Object.hasOwn(messages, value)) return messages[value];
  let match = value.match(/^请填写有效的(.+)（最多 (\d+) 字）$/u);
  if (match) return `Enter a valid ${english(match[1]).toLowerCase()} (up to ${match[2]} characters).`;
  for (const [prefix, translated] of [
    ['审核人改派：', 'Reassigned by reviewer: '],
    ['重新生成方案：', 'New assignment created: '],
    ['拒绝操作：', 'Action blocked: '],
  ]) if (value.startsWith(prefix)) return translated + english(value.slice(prefix.length));
  // Configuration events are structured messages with a free-text reason after the semicolon.
  match = value.match(/^(.+)；(.+)$/u);
  if (match && (match[1].includes(' → ') || value.endsWith('未授予任何业务接收或审核权限'))) {
    const known = match[1].split(/( → | \/ )/u).map(part => messages[part] ?? part).join('');
    return `${known}; ${english(match[2])}`;
  }
  return value;
}
